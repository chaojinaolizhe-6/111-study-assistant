"""把名词表整理成一个独立资料包，供其它 AI 直接引用。

输出目录：入党\党的名词规范\
  README.md
  规范表.md          （完整表，markdown）
  规范表.csv         （完整表，UTF-8 BOM，Excel 可直接开）
  易错对照.csv
  AI-引用规则.md      （短版规则，可直接塞进系统提示）
  + 复制 xlsx / docx 两个人类阅读版
"""
import csv
import importlib.util
import os
import shutil

SRC = r"D:\aaa_D_usual\DSH\111学习助手\tmp\partyclass-20261103\build_terms.py"
OUT = r"D:\aaa_D_usual\DSH\111学习助手\入党\党的名词规范"

spec = importlib.util.spec_from_file_location("terms", SRC)
mod = importlib.util.module_from_spec(spec)
spec.loader.exec_module(mod)

ROWS, WRONG = mod.ROWS, mod.WRONG_ROWS
VERSION = "v1.0（2026-11-04 编制）"

os.makedirs(OUT, exist_ok=True)


def write(name, text):
    p = os.path.join(OUT, name)
    with open(p, "w", encoding="utf-8") as f:
        f.write(text)
    return p


# ---------- 规范表.md ----------
cats = []
for r in ROWS:
    if r[0] not in cats:
        cats.append(r[0])

md = ["# 党的常用名词规范表", "",
      "> 版本：%s ｜ 依据：党章、中央文件原文 ｜ 用途：写党内材料前先查一遍" % VERSION,
      "> 机器可读版：`规范表.csv`；人类阅读版：`党的常用名词规范表-阅读版.docx`", ""]
n = 0
for cat in cats:
    md.append("## " + cat)
    md.append("")
    md.append("| # | 规范表述 | 常见错误写法 | 用法要点 | 依据 |")
    md.append("|---|---|---|---|---|")
    for r in [x for x in ROWS if x[0] == cat]:
        n += 1
        md.append("| %d | **%s** | %s | %s | %s |" % (n, r[1], r[3], r[2], r[4]))
    md.append("")

md.append("## 八、易错速查")
md.append("")
md.append("| # | 错误写法 | 正确写法 | 说明 |")
md.append("|---|---|---|---|")
for i, (bad, good, note) in enumerate(WRONG, start=1):
    md.append("| %d | %s | **%s** | %s |" % (i, bad, good, note))
md.append("")
write("规范表.md", "\n".join(md))

# ---------- CSV ----------
with open(os.path.join(OUT, "规范表.csv"), "w", encoding="utf-8-sig", newline="") as f:
    w = csv.writer(f)
    w.writerow(["序号", "类别", "规范表述", "释义与使用要点", "常见错误写法", "依据"])
    for i, r in enumerate(ROWS, start=1):
        w.writerow([i, r[0], r[1], r[2], r[3], r[4]])

with open(os.path.join(OUT, "易错对照.csv"), "w", encoding="utf-8-sig", newline="") as f:
    w = csv.writer(f)
    w.writerow(["序号", "错误写法", "正确写法", "说明"])
    for i, (bad, good, note) in enumerate(WRONG, start=1):
        w.writerow([i, bad, good, note])

