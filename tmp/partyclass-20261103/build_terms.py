def build_xlsx(path):
    wb = Workbook()
    ws = wb.active
    ws.title = "名词表"

    head_fill = PatternFill("solid", fgColor="8B1E1E")
    head_font = Font(name="微软雅黑", size=11, bold=True, color="FFFFFF")
    body_font = Font(name="微软雅黑", size=10)
    thin = Side(style="thin", color="D9C9C9")
    border = Border(left=thin, right=thin, top=thin, bottom=thin)

    headers = ["序号", "类别", "规范表述", "释义与使用要点", "常见错误写法", "依据"]
    widths = [6, 18, 24, 62, 34, 30]
    for i, (h, w) in enumerate(zip(headers, widths), start=1):
        c = ws.cell(row=1, column=i, value=h)
        c.fill = head_fill
        c.font = head_font
        c.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
        c.border = border
        ws.column_dimensions[get_column_letter(i)].width = w
    ws.row_dimensions[1].height = 28

    band = {"一": "FBEFEF", "二": "FFF7E8", "三": "EEF4FB", "四": "EDF7EE",
            "五": "F6EEF8", "六": "F0F0F0", "七": "EAF6F6"}
    for idx, (cat, term, desc, wrong, src) in enumerate(ROWS, start=1):
        r = idx + 1
        fill = PatternFill("solid", fgColor=band.get(cat[0], "FFFFFF"))
        vals = [idx, cat, term, desc, wrong, src]
        for j, v in enumerate(vals, start=1):
            c = ws.cell(row=r, column=j, value=v)
            c.font = body_font
            c.border = border
            c.fill = fill
            c.alignment = Alignment(vertical="top", wrap_text=True,
                                    horizontal="center" if j in (1,) else "left")

    ws.freeze_panes = "C2"
    ws.auto_filter.ref = "A1:F%d" % (len(ROWS) + 1)

    # 易错对照
    ws2 = wb.create_sheet("易错对照")
    for i, (h, w) in enumerate(zip(["序号", "错误写法", "正确写法", "说明"], [6, 34, 40, 44]), start=1):
        c = ws2.cell(row=1, column=i, value=h)
        c.fill = head_fill
        c.font = head_font
        c.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
        c.border = border
        ws2.column_dimensions[get_column_letter(i)].width = w
    for idx, (bad, good, note) in enumerate(WRONG_ROWS, start=1):
        r = idx + 1
        for j, v in enumerate([idx, bad, good, note], start=1):
            c = ws2.cell(row=r, column=j, value=v)
            c.font = body_font
            c.border = border
            c.alignment = Alignment(vertical="top", wrap_text=True,
                                    horizontal="center" if j == 1 else "left")
    ws2.freeze_panes = "A2"
    ws2.auto_filter.ref = "A1:D%d" % (len(WRONG_ROWS) + 1)

    # 说明
    ws3 = wb.create_sheet("使用说明")
    ws3.column_dimensions["A"].width = 100
    notes = [
        "《党的常用名词规范表》（2026-11-04 编制）",
        "",
        "1. 用途：写思想汇报、心得体会、自评材料、入党材料时，先查这张表，再落笔。",
        "2. 口径：以党章、中央文件原文为准；“释义与使用要点”一列是我按原文压缩的用法提示，不是原文。",
        "3. 依据：标注了文件名和条款的，可直接引用；标注“党内通行做法”的，以学校党组织具体要求为准。",
        "4. 更新：党的二十届五中全会（2026年10月26—29日）刚开完，新增“习近平党建思想”等表述，已收入。",
        "5. 查法：在“名词表”页用 Ctrl+F 搜你要写的词；不确定的先看“常见错误写法”一列有没有你正在用的说法。",
        "6. 这张表可以一直加。遇到表里没有的词，先查共产党员网（12371.cn）的“党务问答”，或中央文件原文。",
    ]
    for i, t in enumerate(notes, start=1):
        c = ws3.cell(row=i, column=1, value=t)
        c.font = Font(name="微软雅黑", size=10 if i > 1 else 12, bold=(i == 1))
        c.alignment = Alignment(wrap_text=True, vertical="top")

    wb.save(path)
    return len(ROWS), len(WRONG_ROWS)


