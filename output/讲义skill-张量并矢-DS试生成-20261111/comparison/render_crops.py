# -*- coding: utf-8 -*-
"""Render the page crops used by the comparison booklet.

Reads comparison/crops.json, renders each clip at the configured DPI from the
frozen source PDFs, checks that the clip's text layer still contains the
promised anchor strings, and writes:

  figs/<key>.png          rendered crop (PNG, RGB)
  cropmeta.tex            LaTeX data macros for labels (page number and clip)
  render-crops.json       machine-readable report for verification

The clip rectangles are PDF points on A4 (595.28 x 841.89). Rendering is
lossless PNG so the crops stay zoom-readable.
"""
import fitz
import json
import os
import sys
import hashlib

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SRC = {
    "old": os.path.join(ROOT, "inputs", "old-handout.pdf"),
    "new": os.path.join(ROOT, "round-04", "handout.pdf"),
}
FIGDIR = os.path.join(HERE, "figs")


def norm(s):
    return s.replace("\x00", "").replace("\r", "").replace("\n", "")


def tex_note(s):
    """Escape characters that the Latin bold font in the crop label lacks."""
    return (s.replace("ε", r"$\varepsilon$")
             .replace("λ", r"$\lambda$")
             .replace("ω", r"$\omega$")
             .replace("′", r"$'$"))


def main():
    with open(os.path.join(HERE, "crops.json"), encoding="utf-8") as f:
        cfg = json.load(f)
    os.makedirs(FIGDIR, exist_ok=True)
    docs = {k: fitz.open(v) for k, v in SRC.items()}
    report = []
    failures = []
    tex_lines = ["% generated by render_crops.py -- do not edit by hand"]
    for c in cfg["crops"]:
        key, pdf, page = c["key"], c["pdf"], c["page"]
        doc = docs[pdf]
        if not (1 <= page <= doc.page_count):
            failures.append(f"{key}: page {page} outside 1..{doc.page_count}")
            continue
        pg = doc[page - 1]
        rect = fitz.Rect(cfg["x0"], c["y0"], cfg["x1"], c["y1"])
        if not (rect.x0 >= 0 and rect.y0 >= 0 and rect.x1 <= pg.rect.x1 and rect.y1 <= pg.rect.y1):
            failures.append(f"{key}: clip {rect} outside page {pg.rect}")
        clip_text = norm(pg.get_text("text", clip=rect))
        missing = [s for s in c["require"] if norm(s) not in clip_text]
        if missing:
            failures.append(f"{key}: missing anchor text {missing}")
        zoom = cfg["dpi"] / 72.0
        pix = pg.get_pixmap(matrix=fitz.Matrix(zoom, zoom), clip=rect, alpha=False)
        out = os.path.join(FIGDIR, key + ".png")
        pix.save(out)
        with open(out, "rb") as fh:
            digest = hashlib.sha256(fh.read()).hexdigest()
        report.append({
            "key": key,
            "pdf": pdf,
            "source": SRC[pdf],
            "page": page,
            "clip_pt": [round(rect.x0, 2), round(rect.y0, 2), round(rect.x1, 2), round(rect.y1, 2)],
            "dpi": cfg["dpi"],
            "pixels": [pix.width, pix.height],
            "png_bytes": os.path.getsize(out),
            "png_sha256": digest,
            "anchors_ok": not missing,
            "missing": missing,
            "note": c["note"],
        })
        label_pdf = "旧稿" if pdf == "old" else "新稿"
        # 5-arg cropdata: key / label / page / clip / note
        tex_lines.append(
            r"\cropdata{%s}{%s}{%d}{y=%d--%d}{%s}" % (
                key, label_pdf, page, c["y0"], c["y1"], tex_note(c["note"])
            )
        )
    with open(os.path.join(HERE, "cropmeta.tex"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(tex_lines) + "\n")
    rows = []
    for r in report:
        label = "旧稿" if r["pdf"] == "old" else "新稿"
        x0, y0, x1, y1 = r["clip_pt"]
        rows.append(
            r"\texttt{%s} & %s & %d & %.0f,%.0f--%.0f,%.0f & %d$\times$%d \\" % (
                r["key"], label, r["page"], x0, y0, x1, y1,
                r["pixels"][0], r["pixels"][1]
            )
        )
    with open(os.path.join(HERE, "croplist.tex"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(rows) + "\n")
    with open(os.path.join(HERE, "render-crops.json"), "w", encoding="utf-8") as f:
        json.dump({
            "dpi": cfg["dpi"],
            "count": len(report),
            "crops": report,
            "failures": failures,
        }, f, ensure_ascii=False, indent=2)
    for r in report:
        print(f"[{'PASS' if r['anchors_ok'] else 'FAIL'}] {r['key']:24s} p{r['page']:<2d} "
              f"{r['pixels'][0]}x{r['pixels'][1]} px  {r['png_bytes']/1024:.0f} KiB")
    if failures:
        print("\nFAILURES:")
        for x in failures:
            print("  -", x)
        return 1
    print(f"\nALL {len(report)} CROPS RENDERED AND ANCHOR-CHECKED")
    return 0


if __name__ == "__main__":
    sys.exit(main())
